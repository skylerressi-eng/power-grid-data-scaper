def get_regions(state):
    """Return ordered list of region names for a state."""
    regions = STATE_REGIONS.get(state)
    if regions:
        return regions
    return [f"All {state}"]


def get_cities_by_region(state, region):
    """Return sorted list of city names for a given state and region.
    If region is 'All Cities' or the state has no region data, returns all cities."""
    all_cities = get_cities(state)
    if not all_cities:
        return []
    if region == "All Cities":
        return all_cities  # already sorted by get_cities()
    city_region_map = STATE_CITY_REGIONS.get(state, {})
    if not city_region_map:
        return all_cities
    result = sorted(c for c in all_cities if city_region_map.get(c) == region)
    # Fallback: if region matches but no cities found (e.g. "All Alaska"), return everything
    return result if result else all_cities
